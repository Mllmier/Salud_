    public void mostrarDatosCitaEnLabels(JTable table, int fila) {
    if (table == null || fila < 0 || fila >= table.getRowCount()) {
        JOptionPane.showMessageDialog(this, "Seleccione una cita válida", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    DefaultTableModel model = (DefaultTableModel) table.getModel();

    lblDocumento3.setText(model.getValueAt(fila, 0).toString());
    lblNombrePaciente3.setText(model.getValueAt(fila, 1).toString());
    lblApellidoPaciente3.setText(model.getValueAt(fila, 2).toString());
    lblEps.setText(model.getValueAt(fila, 3).toString());
    lblTelefono.setText(model.getValueAt(fila, 4).toString());

    lblIdCita3.setText(model.getValueAt(fila, 5).toString());
    lblHoraCita3.setText(model.getValueAt(fila, 6).toString());
    lblMotivoCita3.setText(model.getValueAt(fila, 7).toString());
    lblFechaCita3.setText(model.getValueAt(fila, 8).toString());  
    lblTipoCita3.setText(model.getValueAt(fila, 9).toString());

    lblConsultorio3.setText(model.getValueAt(fila, 10).toString());
    lblEstado3.setText(model.getValueAt(fila, 11).toString());

    lblMedico3.setText(model.getValueAt(fila, 12).toString());
    lblEspecialidad3.setText(model.getValueAt(fila, 14).toString());

    lblSede3.setText(model.getValueAt(fila, 15).toString());
}
  public void setTablaCitasPaciente(JTable tabla) {
    this.tablaCitasPacienteExterna = tabla;
}
  private void cancelarCitaSeleccionada() {
    String idCita = lblIdCita3.getText();

    if (idCita == null || idCita.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "ID de cita no válido", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
            "¿Está seguro que desea cancelar esta cita?",
            "Confirmación", JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        boolean exito = ControllerCitasPaciente.getInstance().cancelarCitaPorId(idCita);

        if (exito) {
            JOptionPane.showMessageDialog(this, "Cita cancelada correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);

            if (tablaCitasPacienteExterna != null) {
                int fila = tablaCitasPacienteExterna.getSelectedRow();
                if (fila != -1) {
                    tablaCitasPacienteExterna.setValueAt("CANCELADA", fila, 11); 
                }
            }

            dispose(); 
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cancelar la cita", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
}


