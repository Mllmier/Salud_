    private void cargarDiagnosticoSeleccionado() {
        int fila = tableEnfermedades.getSelectedRow();
        if (fila >= 0) {
            String diagnostico = tableEnfermedades.getValueAt(fila, 1).toString();
            if (dialogAtender != null) {
                dialogAtender.setDiagnostico(diagnostico);
            }
        }
    }

    public void inicializarListener() {
        tableEnfermedades.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                cargarDiagnosticoSeleccionado();
            }
        });
    }

    
    

