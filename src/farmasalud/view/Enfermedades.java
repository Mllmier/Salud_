    private void btnAgregarEnfermedadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEnfermedadActionPerformed
   int fila = tableEnfermedades.getSelectedRow();
    if (fila >= 0) {
        String nombreEnfermedad = tableEnfermedades.getValueAt(fila, 1).toString(); 
        String sintomas = tableEnfermedades.getValueAt(fila, 3).toString();        

        String diagnosticoCompleto = "Enfermedad: " + nombreEnfermedad + "\nSíntomas: " + sintomas;

        if (dialogAtender != null) {
            dialogAtender.setDiagnostico(diagnosticoCompleto);
            this.dispose(); // Cierra el diálogo Enfermedades si ya seleccionó
        }
    } else {
        JOptionPane.showMessageDialog(this, "Seleccione una enfermedad.");
    }    
    }//GEN-LAST:event_btnAgregarEnfermedadActionPerformed

